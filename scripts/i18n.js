const supportedLanguages = Object.keys(translations);
const languageSelectors = document.querySelectorAll("[data-language-select]");
const experiencePeriods = document.querySelectorAll("[data-experience-period]");
const dateLocales = {
  en: "en-US",
  es: "es-ES",
  pt: "pt-BR",
  fr: "fr-FR",
  de: "de-DE",
  ja: "ja-JP",
  zh: "zh-CN"
};

function getStoredLanguage() {
  try {
    return localStorage.getItem("language");
  } catch {
    return null;
  }
}

function storeLanguage(language) {
  try {
    localStorage.setItem("language", language);
  } catch {
    // Translation still works for this visit when storage is unavailable.
  }
}

function normalizeLanguage(language) {
  const shortCode = language?.toLowerCase().split("-")[0];
  return supportedLanguages.includes(shortCode) ? shortCode : null;
}

function detectLanguage() {
  const storedLanguage = normalizeLanguage(getStoredLanguage());

  if (storedLanguage) {
    return storedLanguage;
  }

  for (const language of navigator.languages || [navigator.language]) {
    const normalizedLanguage = normalizeLanguage(language);

    if (normalizedLanguage) {
      return normalizedLanguage;
    }
  }

  return "en";
}

function translate(key, language = document.documentElement.dataset.language) {
  return translations[language]?.[key] ?? translations.en[key] ?? key;
}

function capitalizeFirst(value) {
  return value.charAt(0).toLocaleUpperCase() + value.slice(1);
}

function updateExperiencePeriod(language) {
  const today = new Date();
  const startDate = new Date(Date.UTC(2022, 8, 1));
  const endDate = new Date(
    Date.UTC(today.getFullYear(), today.getMonth() - 1, 1)
  );
  const formatter = new Intl.DateTimeFormat(dateLocales[language], {
    month: "long",
    year: "numeric",
    timeZone: "UTC"
  });
  const startLabel = capitalizeFirst(formatter.format(startDate));
  const endLabel = capitalizeFirst(formatter.format(endDate));

  experiencePeriods.forEach((period) => {
    period.textContent = `${startLabel} — ${endLabel}`;
  });
}

function setLanguage(language, persist = false) {
  const normalizedLanguage = normalizeLanguage(language) || "en";

  document.documentElement.dataset.language = normalizedLanguage;
  document.documentElement.lang = normalizedLanguage === "zh" ? "zh-Hans" : normalizedLanguage;
  document.title = translate("meta.title", normalizedLanguage);
  updateExperiencePeriod(normalizedLanguage);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = translate(element.dataset.i18n, normalizedLanguage);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    element.alt = translate(element.dataset.i18nAlt, normalizedLanguage);
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute(
      "aria-label",
      translate(element.dataset.i18nAriaLabel, normalizedLanguage)
    );
  });

  document.querySelectorAll("[data-i18n-content]").forEach((element) => {
    element.setAttribute(
      "content",
      translate(element.dataset.i18nContent, normalizedLanguage)
    );
  });

  languageSelectors.forEach((selector) => {
    selector.value = normalizedLanguage;
    selector.setAttribute(
      "aria-label",
      translate("accessibility.language", normalizedLanguage)
    );

    const currentLanguage = selector
      .closest(".language-selector")
      ?.querySelector("[data-language-current]");

    if (currentLanguage) {
      currentLanguage.textContent = selector.options[selector.selectedIndex].text;
    }
  });

  if (persist) {
    storeLanguage(normalizedLanguage);
  }

  document.dispatchEvent(
    new CustomEvent("languagechange", { detail: { language: normalizedLanguage } })
  );
}

languageSelectors.forEach((selector) => {
  selector.addEventListener("change", (event) => {
    setLanguage(event.target.value, true);
  });
});

window.i18n = {
  setLanguage,
  t: (key) => translate(key)
};

setLanguage(detectLanguage());
